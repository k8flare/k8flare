// genLeanClient writes pkg/leanclient/gen/<group><version>.go per
// leanClientGroups entry: one struct + constructor per type, implementing
// its client-go XInterface's CRUD/Watch methods via pkg/leanclient's
// verb/watch helpers (never through a runtime.Scheme -- see
// pkg/leanclient/leanclient.go's doc comment), plus Apply/ApplyStatus
// panic stubs (required by the interface; never called -- zero
// Server-Side Apply use in this repo's controllers/scheduler, confirmed
// by grep). Each type's Extras field (above) supplies its remaining,
// non-uniform XExpansion/base-interface methods.
func genLeanClient(root string) error {
	for _, group := range leanClientGroups {
		var b strings.Builder
		fmt.Fprintf(&b, "//go:build js && wasm\n\n// %s\n\npackage %s\n\n", generatedHeader, group.GoPackage)

		b.WriteString("import (\n")
		b.WriteString("\t\"context\"\n\n")
		b.WriteString("\tmetav1 \"k8s.io/apimachinery/pkg/apis/meta/v1\"\n")
		b.WriteString("\t\"k8s.io/apimachinery/pkg/runtime/schema\"\n")
		b.WriteString("\t\"k8s.io/apimachinery/pkg/types\"\n")
		b.WriteString("\tapimachinerywatch \"k8s.io/apimachinery/pkg/watch\"\n")
		b.WriteString("\trestclient \"k8s.io/client-go/rest\"\n\n")
		fmt.Fprintf(&b, "\t%s %q\n", group.TypedPackageAlias, group.TypedPackagePath)
		b.WriteString("\n\t\"github.com/k8flare/k8flare/pkg/leanclient\"\n")
		seenAPIPkg := map[string]bool{}
		seenApplyPkg := map[string]bool{}
		for _, t := range group.Types {
			if !seenAPIPkg[t.APIPackagePath] {
				fmt.Fprintf(&b, "\t%s %q\n", t.APIPackageAlias, t.APIPackagePath)
				seenAPIPkg[t.APIPackagePath] = true
			}
		}
		for _, t := range group.Types {
			if !seenApplyPkg[t.ApplyConfigPackagePath] {
				fmt.Fprintf(&b, "\t%s %q\n", t.ApplyConfigPackageAlias, t.ApplyConfigPackagePath)
				seenApplyPkg[t.ApplyConfigPackagePath] = true
			}
		}
		seenExtra := map[string]bool{}
		for _, t := range group.Types {
			for _, imp := range t.ExtraImports {
				if !seenExtra[imp] {
					fmt.Fprintf(&b, "\t%s\n", imp)
					seenExtra[imp] = true
				}
			}
		}
		b.WriteString(")\n\n")

		fmt.Fprintf(&b, "// RESTClientFor builds this group's *rest.RESTClient, sharing cfg's Transport.\n")
		fmt.Fprintf(&b, "func RESTClientFor(cfg *restclient.Config) (*restclient.RESTClient, error) {\n")
		fmt.Fprintf(&b, "\treturn leanclient.RESTClientFor(cfg, %q, %s)\n", group.APIPath, group.GroupVersion)
		b.WriteString("}\n\n")

		writeLeanClientGroupAggregate(&b, group)

		for _, t := range group.Types {
			writeLeanClientType(&b, t, group.TypedPackageAlias, group.GroupVersion)
		}

		outPath := fmt.Sprintf("%s/pkg/leanclient/gen/%s/%s.go", root, group.GoPackage, group.GoPackage)
		if err := writeGoFile(outPath, []byte(b.String())); err != nil {
			return fmt.Errorf("%s: %w", group.GoPackage, err)
		}
	}
	return nil
}

func capitalize(s string) string {
	if s == "" {
		return s
	}
	return strings.ToUpper(s[:1]) + s[1:]
}

// writeLeanClientGroupAggregate emits Client, the group-level struct
// satisfying e.g. corev1client.CoreV1Interface (RESTClient() + one
// XsGetter method per type) by delegating each XsGetter method to the
// matching NewXs constructor below.
func writeLeanClientGroupAggregate(b *strings.Builder, group leanClientGroup) {
	b.WriteString("type Client struct {\n\trc restclient.Interface\n}\n\n")
	fmt.Fprintf(b, "var _ %s.%s = (*Client)(nil)\n\n", group.TypedPackageAlias, group.GroupInterface)

	b.WriteString("func New(cfg *restclient.Config) (*Client, error) {\n")
	b.WriteString("\trc, err := RESTClientFor(cfg)\n\tif err != nil {\n\t\treturn nil, err\n\t}\n")
	b.WriteString("\treturn &Client{rc: rc}, nil\n}\n\n")

	b.WriteString("func (c *Client) RESTClient() restclient.Interface { return c.rc }\n\n")

	for _, t := range group.Types {
		// The XsGetter method name matches t.Receiver capitalized, not
		// simply Kind+"s" -- Endpoints is already plural (EndpointsGetter.
		// Endpoints, not "Endpointss"), so this must follow client-go's
		// own generated method name (== this repo's Receiver, chosen to
		// match it) rather than mechanically appending "s" to Kind.
		getterMethod := capitalize(t.Receiver)
		fmt.Fprintf(b, "func (c *Client) %s(", getterMethod)
		if t.Namespaced {
			fmt.Fprintf(b, "namespace string) %s.%sInterface {\n", group.TypedPackageAlias, t.Kind)
			fmt.Fprintf(b, "\treturn New%s(c.rc, namespace)\n}\n\n", getterMethod)
		} else {
			fmt.Fprintf(b, ") %s.%sInterface {\n", group.TypedPackageAlias, t.Kind)
			fmt.Fprintf(b, "\treturn New%s(c.rc)\n}\n\n", getterMethod)
		}
	}

	if group.OtherGetterStubs != "" {
		b.WriteString(group.OtherGetterStubs)
		b.WriteString("\n")
	}
}

func writeLeanClientType(b *strings.Builder, t leanClientType, typedPackageAlias, groupVersion string) {
	obj := t.APIPackageAlias + "." + t.Kind
	list := obj + "List"
	apply := t.ApplyConfigPackageAlias + "." + t.Kind + "ApplyConfiguration"
	// gvk is a literal schema.GroupVersionKind construction, spliced into
	// each Create/Update/UpdateStatus call below so leanclient.Create et
	// al. can stamp Kind/APIVersion onto the object before marshaling --
	// see pkg/leanclient/verbs.go's setTypeMeta doc comment for why this
	// is required (the k8flare apiserver's decoder 400s without it).
	gvk := fmt.Sprintf("%s.WithKind(%q)", groupVersion, t.Kind)

	fmt.Fprintf(b, "type %s struct {\n\tclient restclient.Interface\n\tns string\n}\n\n", t.Receiver)

	// Compile-time interface satisfaction check: if a k8s.io/client-go
	// bump adds/changes a method on this type's XInterface (declared in
	// the pruned pkg/clientgo-lean-overlays mirror), this fails
	// go build here instead of failing silently at runtime (same
	// reasoning as pkg/apiserver/apidef.Table's New/NewList closures).
	fmt.Fprintf(b, "var _ %s.%sInterface = (*%s)(nil)\n\n", typedPackageAlias, t.Kind, t.Receiver)

	nsArg := ""
	nsField := `""`
	if t.Namespaced {
		nsArg = "ns string"
		nsField = "ns"
	}
	fmt.Fprintf(b, "func New%s(c restclient.Interface", capitalize(t.Receiver))
	if nsArg != "" {
		fmt.Fprintf(b, ", %s", nsArg)
	}
	fmt.Fprintf(b, ") *%s {\n\treturn &%s{client: c, ns: %s}\n}\n\n", t.Receiver, t.Receiver, nsField)

	fmt.Fprintf(b, "func (c *%s) Create(ctx context.Context, obj *%s, opts metav1.CreateOptions) (*%s, error) {\n", t.Receiver, obj, obj)
	fmt.Fprintf(b, "\treturn leanclient.Create(ctx, c.client, %q, c.ns, obj, %s, opts)\n}\n\n", t.Resource, gvk)

	fmt.Fprintf(b, "func (c *%s) Update(ctx context.Context, obj *%s, opts metav1.UpdateOptions) (*%s, error) {\n", t.Receiver, obj, obj)
	fmt.Fprintf(b, "\treturn leanclient.Update(ctx, c.client, %q, c.ns, obj.Name, obj, %s, opts)\n}\n\n", t.Resource, gvk)

	if t.HasUpdateStatus {
		fmt.Fprintf(b, "func (c *%s) UpdateStatus(ctx context.Context, obj *%s, opts metav1.UpdateOptions) (*%s, error) {\n", t.Receiver, obj, obj)
		fmt.Fprintf(b, "\treturn leanclient.UpdateSubresource(ctx, c.client, %q, c.ns, obj.Name, \"status\", obj, %s, opts)\n}\n\n", t.Resource, gvk)
	}

	fmt.Fprintf(b, "func (c *%s) Delete(ctx context.Context, name string, opts metav1.DeleteOptions) error {\n", t.Receiver)
	fmt.Fprintf(b, "\treturn leanclient.Delete(ctx, c.client, %q, c.ns, name, opts)\n}\n\n", t.Resource)

	fmt.Fprintf(b, "func (c *%s) DeleteCollection(ctx context.Context, opts metav1.DeleteOptions, listOpts metav1.ListOptions) error {\n", t.Receiver)
	fmt.Fprintf(b, "\treturn leanclient.DeleteCollection(ctx, c.client, %q, c.ns, opts, listOpts)\n}\n\n", t.Resource)

	fmt.Fprintf(b, "func (c *%s) Get(ctx context.Context, name string, opts metav1.GetOptions) (*%s, error) {\n", t.Receiver, obj)
	fmt.Fprintf(b, "\treturn leanclient.Get[%s](ctx, c.client, %q, c.ns, name, opts)\n}\n\n", obj, t.Resource)

	fmt.Fprintf(b, "func (c *%s) List(ctx context.Context, opts metav1.ListOptions) (*%s, error) {\n", t.Receiver, list)
	fmt.Fprintf(b, "\treturn leanclient.List[%s](ctx, c.client, %q, c.ns, opts)\n}\n\n", list, t.Resource)

	fmt.Fprintf(b, "func (c *%s) Watch(ctx context.Context, opts metav1.ListOptions) (apimachinerywatch.Interface, error) {\n", t.Receiver)
	fmt.Fprintf(b, "\treturn leanclient.Watch(ctx, c.client, %q, c.ns, opts, func() *%s { return &%s{} })\n}\n\n", t.Resource, obj, obj)

	fmt.Fprintf(b, "func (c *%s) Patch(ctx context.Context, name string, pt types.PatchType, data []byte, opts metav1.PatchOptions, subresources ...string) (*%s, error) {\n", t.Receiver, obj)
	fmt.Fprintf(b, "\treturn leanclient.Patch[%s](ctx, c.client, %q, c.ns, name, pt, data, opts, subresources...)\n}\n\n", obj, t.Resource)

	fmt.Fprintf(b, "func (c *%s) Apply(ctx context.Context, obj *%s, opts metav1.ApplyOptions) (*%s, error) {\n", t.Receiver, apply, obj)
	fmt.Fprintf(b, "\tpanic(%q)\n}\n\n", "leanclient: Server-Side Apply not implemented (unused by this repo's controllers/scheduler)")

	if t.HasUpdateStatus {
		fmt.Fprintf(b, "func (c *%s) ApplyStatus(ctx context.Context, obj *%s, opts metav1.ApplyOptions) (*%s, error) {\n", t.Receiver, apply, obj)
		fmt.Fprintf(b, "\tpanic(%q)\n}\n\n", "leanclient: Server-Side Apply not implemented (unused by this repo's controllers/scheduler)")
	}

	if t.Extras != "" {
		b.WriteString(t.Extras)
		b.WriteString("\n")
	}
}
