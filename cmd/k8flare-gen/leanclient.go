// leanClientType describes one API type pkg/leanclient/gen must implement
// a client-go XInterface for. This table is this generator's own small
// hand-written source of truth (mirrors pkg/apiserver/apidef.Table's
// role for the apiserver side) -- see pkg/leanclient/leanclient.go's doc
// comment and pkg/clientgo-lean-overlays/README.md for why this
// package exists at all (client-go's own generated typed clients cost
// ~45MiB of linked GOOS=js/wasm code regardless of scheme scope).
//
// Limited to the 13 types this repo's real, unmodified upstream
// controllers (pkg/controller/{replicaset,deployment,daemon,job,cronjob,
// endpoint,endpointslice,nodeipam,nodelifecycle,tainteviction}), scheduler
// (pkg/scheduler), and every controller/scheduler's
// record.EventBroadcaster (client-go/tools/events, wired up right after
// Run()) actually construct clients/informers for (confirmed by grep, not
// guessed) -- adding a resource here requires a
// matching hand-curated interface-only extraction in
// pkg/clientgo-lean-overlays/kubernetes/typed/<group>/<version>/
// and pkg/clientgo-lean-overlays/applyconfigurations/<group>/<version>/
// first (see that directory's README.md), since the generated code below
// implements interfaces declared there, not upstream's unpruned ones.
type leanClientType struct {
	// Kind is the Go type name, e.g. "Pod".
	Kind string
	// Receiver is the unexported plural receiver name client-go's own
	// generated code uses for this type, e.g. "pods" -- kept identical so
	// this package's shape matches upstream's for anyone diffing them.
	Receiver string
	// Resource is the plural lowercase URL path segment, e.g. "pods".
	Resource string
	// Namespaced is false for cluster-scoped types (Node).
	Namespaced bool
	// HasUpdateStatus is whether this type's XInterface declares
	// UpdateStatus (client-gen omits it for types annotated
	// +genclient:noStatus upstream -- Endpoints, ControllerRevision,
	// EndpointSlice, Lease).
	HasUpdateStatus bool

	// APIPackageAlias/APIPackagePath: k8s.io/api/<group>/<version>, the
	// concrete object type's own package.
	APIPackageAlias string
	APIPackagePath  string
	// ApplyConfigPackageAlias/ApplyConfigPackagePath: this repo's pruned
	// pkg/clientgo-lean-overlays/applyconfigurations/<group>/<version>
	// mirror -- only ever referenced for Apply/ApplyStatus's parameter type
	// (see leanclient.go's doc comment for why a real implementation isn't
	// provided: Server-Side Apply is unused by every controller/scheduler
	// this repo enables).
	ApplyConfigPackageAlias string
	ApplyConfigPackagePath  string

	// ExtraImports/Extras: this type's XExpansion interface methods
	// (Pod's Bind/Evict*/GetLogs/ProxyGet, Node's PatchStatus, Service's
	// ProxyGet) plus any non-CRUD method the base XInterface itself
	// declares (ReplicaSet/Deployment's ApplyScale) -- a handful of
	// varied, one-off signatures too irregular for the uniform
	// writeLeanClientType template above, hand-written once here and
	// spliced verbatim into the generated file (still emitted by the
	// generator, still regenerated by `go run ./cmd/k8flare-gen`, just
	// not templated). Only Pod's Bind has a real implementation --
	// confirmed by grep, it's the only one this repo's real upstream
	// scheduler (pkg/scheduler/framework/plugins/defaultbinder) actually
	// calls. Every other method here is an intentional panic stub.
	ExtraImports []string
	Extras       string
}

// leanClientGroup is one client-go typed/<group>/<version> package: the
// GroupVersion's REST API path pieces, plus the types within it.
type leanClientGroup struct {
	// GoPackage is this generated file's own package suffix, e.g. "corev1".
	GoPackage string
	// APIPath is "/api" for the legacy core group, "/apis" for every other
	// group (matches client-go's own setConfigDefaults per group).
	APIPath string
	// GroupVersion is schema.GroupVersion's literal Go construction, e.g.
	// `schema.GroupVersion{Group: "", Version: "v1"}`.
	GroupVersion string
	// TypedPackageAlias/TypedPackagePath: this repo's pruned
	// pkg/clientgo-lean-overlays/kubernetes/typed/<group>/<version>
	// mirror, declaring the XInterface/XGetter this file implements.
	TypedPackageAlias string
	TypedPackagePath  string
	// GroupInterface is this group's aggregate interface name declared in
	// the typed package above, e.g. "CoreV1Interface".
	GroupInterface string
	// OtherGetterStubs: panic-stub methods for this group's Getters
	// *beyond* the types in Types below -- GroupInterface's full upstream
	// width (e.g. CoreV1Interface has 16 Getters; this repo's Clientset
	// implements 4 for real) requires every other Getter to exist on
	// *Client too, even though nothing calls them (confirmed by grep --
	// see leanclient.go's package doc comment on why the full width is
	// unavoidable once pkg/scheduler.New's aggregate
	// informers.SharedInformerFactory parameter is in the same binary).
	// Raw method source, spliced in by writeLeanClientGroupAggregate.
	OtherGetterStubs string

	Types []leanClientType
}

