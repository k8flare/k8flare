// Command genresources writes packages/apiserver-registry/zz_generated_resources.go from
// the discovery documents shipped with the pinned Kubernetes module
// (api/discovery/*.json), filtered to the resources this apiserver serves.
// Names, kinds, verbs, short names and categories therefore come from
// upstream, and a version bump that changes them shows up as a diff.
package main

import (
	"encoding/json"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"sort"
	"strings"
)

// apiResource is the subset of metav1.APIResource the generator reads,
// kept local so this module stays dependency-free.
type apiResource struct {
	Name         string   `json:"name"`
	SingularName string   `json:"singularName"`
	Namespaced   bool     `json:"namespaced"`
	Kind         string   `json:"kind"`
	Verbs        []string `json:"verbs"`
	ShortNames   []string `json:"shortNames"`
	Categories   []string `json:"categories"`
}

type apiResourceList struct {
	Resources []apiResource `json:"resources"`
}

const (
	module  = "github.com/k3s-io/kubernetes"
	version = "v1.36.4-k3s1"
)

// served lists the resources per group/version. A resource's /status
// subresource is included when upstream serves one; pods/log is the only
// other subresource.
var served = []struct {
	gv        string
	resources []string
}{
	{"v1", []string{"configmaps", "events", "namespaces", "nodes", "pods", "pods/log", "secrets", "serviceaccounts", "services"}},
	{"coordination.k8s.io/v1", []string{"leases"}},
	{"discovery.k8s.io/v1", []string{"endpointslices"}},
	{"node.k8s.io/v1", []string{"runtimeclasses"}},
	{"storage.k8s.io/v1", []string{"csidrivers", "csinodes"}},
	{"authentication.k8s.io/v1", []string{"tokenreviews"}},
	{"authorization.k8s.io/v1", []string{"selfsubjectaccessreviews", "subjectaccessreviews"}},
}

func main() {
	root, err := exec.Command("git", "rev-parse", "--show-toplevel").Output()
	check(err)
	dir, err := moduleDir()
	check(err)
	var out strings.Builder
	out.WriteString("// Code generated by scripts/genresources from " + module + "@" + version + " api/discovery. DO NOT EDIT.\n\n")
	out.WriteString("package registry\n\nimport (\n\tmetav1 \"k8s.io/apimachinery/pkg/apis/meta/v1\"\n\t\"k8s.io/apimachinery/pkg/runtime/schema\"\n)\n\n")
	out.WriteString("// Served is the API surface, filtered from upstream's discovery documents.\nvar Served = []ServedGroupVersion{\n")
	for _, s := range served {
		list, err := load(dir, s.gv)
		check(err)
		byName := map[string]apiResource{}
		for _, r := range list.Resources {
			byName[r.Name] = r
		}
		group, ver := "", s.gv
		if i := strings.Index(s.gv, "/"); i >= 0 {
			group, ver = s.gv[:i], s.gv[i+1:]
		}
		fmt.Fprintf(&out, "\t{GV: schema.GroupVersion{Group: %q, Version: %q}, Resources: []metav1.APIResource{\n", group, ver)
		var names []string
		for _, name := range s.resources {
			names = append(names, name)
			if _, ok := byName[name+"/status"]; ok && !strings.Contains(name, "/") {
				names = append(names, name+"/status")
			}
		}
		sort.Strings(names)
		for _, name := range names {
			r, ok := byName[name]
			if !ok {
				check(fmt.Errorf("%s: %s is not in upstream discovery", s.gv, name))
			}
			fmt.Fprintf(&out, "\t\t{Name: %q, SingularName: %q, Namespaced: %v, Kind: %q, Verbs: %s, ShortNames: %s, Categories: %s},\n",
				r.Name, r.SingularName, r.Namespaced, r.Kind, goStrings("metav1.Verbs", r.Verbs), goStrings("[]string", r.ShortNames), goStrings("[]string", r.Categories))
		}
		out.WriteString("\t}},\n")
	}
	out.WriteString("}\n")
	target := filepath.Join(strings.TrimSpace(string(root)), "packages/apiserver-registry/zz_generated_resources.go")
	check(os.WriteFile(target, []byte(out.String()), 0o644))
	fmt.Println("genresources: wrote", target)
}

func goStrings(typ string, values []string) string {
	if len(values) == 0 {
		return "nil"
	}
	quoted := make([]string, len(values))
	for i, v := range values {
		quoted[i] = fmt.Sprintf("%q", v)
	}
	return typ + "{" + strings.Join(quoted, ", ") + "}"
}

func load(dir, gv string) (*apiResourceList, error) {
	name := "apis__" + strings.ReplaceAll(gv, "/", "__") + ".json"
	if !strings.Contains(gv, "/") {
		name = "api__" + gv + ".json"
	}
	data, err := os.ReadFile(filepath.Join(dir, "api/discovery", name))
	if err != nil {
		return nil, err
	}
	var list apiResourceList
	return &list, json.Unmarshal(data, &list)
}

func moduleDir() (string, error) {
	cmd := exec.Command("go", "mod", "download", "-json", module+"@"+version)
	cmd.Dir = os.TempDir()
	cmd.Env = append(os.Environ(), "GOFLAGS=-mod=mod", "GO111MODULE=on")
	out, err := cmd.Output()
	if err != nil {
		return "", err
	}
	var info struct{ Dir string }
	if err := json.Unmarshal(out, &info); err != nil {
		return "", err
	}
	return info.Dir, nil
}

func check(err error) {
	if err != nil {
		fmt.Fprintln(os.Stderr, "genresources:", err)
		os.Exit(1)
	}
}
